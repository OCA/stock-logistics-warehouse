from odoo import Command
from odoo.tests.common import TransactionCase


class TestAccountMoveLineStockInfo(TransactionCase):
    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        cls.env = cls.env(context=dict(cls.env.context, tracking_disable=True))
        cls.company = cls.env["res.company"].create({"name": "Test Company"})
        cls.env["account.chart.template"]._load(
            "generic_coa", cls.company, install_demo=False
        )
        cls.env = cls.env(
            context=dict(cls.env.context, allowed_company_ids=cls.company.ids)
        )
        cls.company = cls.company.with_env(cls.env)
        cls.warehouse = cls.env["stock.warehouse"].search(
            [("company_id", "=", cls.company.id)], limit=1
        )
        cls.location_stock = cls.warehouse.lot_stock_id
        cls.location_supplier = cls.env.ref("stock.stock_location_suppliers")
        cls.location_customer = cls.env.ref("stock.stock_location_customers")
        cls.picking_type_in = cls.warehouse.in_type_id
        cls.picking_type_out = cls.warehouse.out_type_id
        cls.account_external = cls.env["account.account"].create(
            {
                "name": "Stock External",
                "code": "STOCKEXT",
                "account_type": "expense",
            }
        )
        (
            cls.location_supplier | cls.location_customer
        ).valuation_account_id = cls.account_external
        product_ctg = cls.env["product.category"].create(
            {
                "name": "test_product_ctg",
                "property_valuation": "real_time",
                "property_cost_method": "standard",
                "property_stock_valuation_account_id": (
                    cls.company.account_stock_valuation_id.id
                ),
            }
        )
        cls.product = cls.env["product.product"].create(
            {
                "name": "test_product",
                "categ_id": product_ctg.id,
                "type": "consu",
                "is_storable": True,
                "standard_price": 1.0,
                "list_price": 1.0,
            }
        )
        cls.stock_manager = cls._create_user(
            "stock_manager",
            cls.env.ref("stock.group_stock_manager")
            | cls.env.ref("account.group_account_invoice"),
        )
        cls.account_invoice = cls._create_user(
            "account_invoice", cls.env.ref("account.group_account_invoice")
        )
        cls.account_manager = cls._create_user(
            "account_manager", cls.env.ref("account.group_account_manager")
        )

    @classmethod
    def _create_user(cls, login, groups):
        return (
            cls.env["res.users"]
            .with_context(no_reset_password=True)
            .create(
                {
                    "name": "Test User",
                    "login": login,
                    "email": "test@yourcompany.com",
                    "company_id": cls.company.id,
                    "company_ids": [Command.set(cls.company.ids)],
                    "group_ids": [Command.set(groups.ids)],
                }
            )
        )

    def _create_and_validate_picking(self, picking_type, location, location_dest):
        picking = (
            self.env["stock.picking"]
            .with_user(self.stock_manager)
            .create(
                {
                    "picking_type_id": picking_type.id,
                    "location_id": location.id,
                    "location_dest_id": location_dest.id,
                    "move_ids": [
                        Command.create(
                            {
                                "product_id": self.product.id,
                                "product_uom": self.product.uom_id.id,
                                "product_uom_qty": 3,
                                "location_id": location.id,
                                "location_dest_id": location_dest.id,
                            }
                        )
                    ],
                }
            )
        )
        picking.action_confirm()
        picking.move_ids.quantity = 1
        picking.move_ids.picked = True
        picking._action_done()
        return picking

    def test_account_move_line_stock_move(self):
        """Test that processing an incoming picking the account moves
        generated by the picking moves will contain the stock move.
        """
        picking_in = self._create_and_validate_picking(
            self.picking_type_in, self.location_supplier, self.location_stock
        )
        move_in = picking_in.move_ids
        self.assertEqual(len(move_in.account_move_line_ids), 2)
        self.assertEqual(move_in.account_move_line_ids.move_id, move_in.account_move_id)
        picking_out = self._create_and_validate_picking(
            self.picking_type_out, self.location_stock, self.location_customer
        )
        move_out = picking_out.move_ids
        self.assertEqual(len(move_out.account_move_line_ids), 2)
        account_move_line = move_in.account_move_line_ids[:1]
        self.assertEqual(
            account_move_line.with_user(self.account_invoice).stock_move_id, move_in
        )
        self.assertEqual(
            account_move_line.with_user(self.account_manager).stock_move_id, move_in
        )
